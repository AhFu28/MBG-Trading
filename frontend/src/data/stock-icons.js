export const getStockConfig = (ticker, market = 'IDX') => {
  if (!ticker) return null;
  const clean = String(ticker).toUpperCase().replace(/^(IDX:|NASDAQ:|NYSE:)/, '').replace(/\.JK$/, '').trim();
  if (market === 'IDX' || market === 'STOCK') {
    return IDX_STOCKS_CONFIG[clean] || { domain: `${clean.toLowerCase()}.co.id`, color: '#1e3a8a', fg: '#FFFFFF', name: clean };
  }
  return US_STOCKS_CONFIG[clean] || { domain: `${clean.toLowerCase()}.com`, color: '#0f172a', fg: '#FFFFFF', name: clean };
};
