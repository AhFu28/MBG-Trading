export const cleanCryptoSymbol = (symbol) => {
  if (!symbol) return '';
  let s = String(symbol).toUpperCase().trim();
  s = s.replace(/^(BINANCE:|OKX:|BYBIT:|GATEIO:)/, '');
  s = s.replace(/(\.P|\/USDT|USDT|\/USD|USD|\/BUSD|BUSD|\/BTC)$/, '');
  s = s.replace(/1000/, '');
  return s;
};

export const getCryptoBrand = (symbol) => {
  const s = cleanCryptoSymbol(symbol);
  return CRYPTO_BRAND_COLORS[s] || { bg: '#3B82F6', fg: '#FFFFFF', name: s };
};

export const getCryptoIcon = (symbol) => {
  const s = cleanCryptoSymbol(symbol);
  return CRYPTO_ICONS[s] || null;
};

